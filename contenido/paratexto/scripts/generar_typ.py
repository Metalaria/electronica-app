CABECERA = '// {f}: generated by scripts/generar_typ.py from datos/{p}.json and redaccion/. Do not edit by hand.\n'


def num_parte(p):
    return str(INDICE['partes'][p].get('num'))


def contenido(h):
    return '[' + html_a_typst(h) + ']'


# printed number of a design problem → its label (4.1, decisiones E3: the self-assessment cites problems with #nr)
PROBLEMAS = {v['num']: k for k, v in sorted(REFS.items()) if k.startswith('prob-') and v.get('num')}


def con_nr(typ):
    """«Problema 39.B» in a Typst text as the book writes it since 4.1: «Problema #nr("prob-38.B")»."""
    return re.sub(r'\b([Pp]roblema) (\d+\.[A-Z])\b', lambda m: f'{m.group(1)} #nr("{PROBLEMAS[m.group(2)]}")'
                  if m.group(2) in PROBLEMAS else m.group(0), typ)


def texto(s):
    return '[' + escapar(' '.join(s.split())) + ']'


def tupla(items):
    items = list(items)
    if not items:
        return '()'
    return '(' + ', '.join(items) + (',)' if len(items) == 1 else ')')


def referencia(l):
    e = LECTURAS[l]
    ed = f", {e['edicion']}" if e.get('edicion') else ''
    return f"{e['autor']}, «{e['titulo']}», {e['editorial']}{ed}."


# ------------------------------------------------------------------------------------- per chapter
def typ_parte(d, r):
    p = d['parte']
    out = [CABECERA.format(f=f'{p}.typ', p=p), '#import "paratexto.typ": *', '']
    # difficulty
    niv = ', '.join(f'"{e["id"]}": {e["nivel"]}' for e in d['dificultad'])
    out.append(f'#let niveles = ({niv or ":"})')
    # opener
    obj = ', '.join(texto(o) for o in r['objetivos'])
    out.append(f'#let objetivos-cap = objetivos({obj})')
    ter = ', '.join(f'({cadena(t["termino"])}, {cadena(t["ref"]) if t["ref"] else "none"}, '
                    f'{cadena(t["ref_num"]) if t["ref_num"] else "none"})' for t in d['terminos_clave'])
    out.append(f'#let terminos = terminos-clave({ter})' if ter else '#let terminos = none')
    mats = tupla(cadena(MATERIAS.get(m, m)) for m in r['grado']['materias'])
    comps = tupla(f'({cadena(c)}, {cadena(CORTO[c])})' for c in r['grado']['competencias'])
    out.append(f'#let grado = grado-capitulo(materias: {mats}, competencias: {comps})'
               if r['grado']['materias'] or r['grado']['competencias'] else '#let grado = none')
    out.append('#let inicio = sin-glosario({ objetivos-cap; terminos; grado })')
    out.append('')
    # closing
    out.append(f'#let resumen = resumen-capitulo({texto(r["resumen"])})')
    filas = []
    for f in d['formulas']:
        filas.append(f'({contenido(f["nombre"])}, $ {f["fuente"]} $, {cadena(f["seccion"])}, '
                     f'{cadena(f["seccion_num"])}, {"true" if f["tarjeta"] else "false"})')
    out.append(f'#let formulas = formulas-capitulo({tupla(filas)})' if filas else '#let formulas = none')
    preg = []
    fuera = set(r.get('autoev_fuera') or [])
    d = {**d, 'autoevaluacion': [q for q in d['autoevaluacion'] if q['id'] not in fuera]}
    for q in d['autoevaluacion']:
        if q['tipo'] == 'opcion':
            ops = tupla(contenido(o) for o in q['opciones'])
            preg.append(f'({cadena(q["id"])}, {con_nr(contenido(q["enunciado"]))}, {ops}, none)')
        else:
            preg.append(f'({cadena(q["id"])}, {con_nr(contenido(q["enunciado"]))}, none, {cadena(q["unidad"] or "")})')
    out.append(f'#let autoev = autoevaluacion({cadena(p)}, {tupla(preg)})' if preg else '#let autoev = none')
    nor = []
    for n in d['normas']:
        refs = tupla(f'({cadena(a)}, {cadena(b)})' for a, b in zip(n['refs'], n['refs_num']))
        nor.append(f'({texto(n["cita"])}, {texto(n["contexto"])}, {refs})')
    lec = tupla(f'({texto(referencia(l))}, {cadena("G" if LECTURAS[l]["origen"] == "G" else "sugerencia")})'
                for l in r.get('lecturas', []))
    out.append(f'#let normas = normas-referencias(normas: {tupla(nor)}, lecturas: {lec})')
    out.append('#let cierre = { resumen; normas; formulas; autoev }')
    out.append('')
    # solutions of the self-assessment, collected by tomo<N>.typ
    sols = []
    for q in d['autoevaluacion']:
        if q['tipo'] == 'opcion':
            letra = 'abcdef'[q['correcta']]
            resp = f'[{letra}) {html_a_typst(q["opciones"][q["correcta"]])}]'
        else:
            u = (' ' + q['unidad']) if q['unidad'] else ''
            resp = texto(q['valor_texto'] + u)
        num = (q['ref_num'] or REFS.get(q['ref'], {}).get('num')
               or re.sub(r'^ap([A-J])-(\d+)$', r'\1.\2', q['ref'] or ''))
        sols.append(f'({cadena(q["id"])}, {resp}, {con_nr(contenido(q["explicacion"]))}, {cadena(q["ref"] or "")}, '
                    f'{cadena(num)})')
    etq = NOMBRE_PARTE[p]
    out.append(f'#let soluciones = ({cadena(p)}, [{etq}], {texto(d["titulo"])}, {tupla(sols)})')
    # (1.2: the book's own line of a drafted piece it changed by hand)
    propias = r.get('typst') or {}
    out = [propias.get(m.group(1), linea) if (m := re.match(r'^#let ([\w-]+) = ', linea)) else linea for linea in out]
    return '\n'.join(out) + '\n'


# ------------------------------------------------------------------------------------- per volume
def typ_tomo(tomo, partes):
    alias = {p: 'p' + re.sub(r'[^0-9a-zA-Z]', '', p) for p in partes}
    out = [CABECERA.format(f=f'tomo{tomo}.typ', p=f'indice-tomo{tomo}'), '#import "paratexto.typ": *']
    for p in partes:
        out.append(f'#import "{p}.typ" as {alias[p]}')
    out.append('')
    con_autoev = [p for p in partes if json.load(open(os.path.join(DATOS, f'{p}.json'), encoding='utf-8'))['autoevaluacion']]
    out.append(f'#let soluciones = soluciones-autoevaluacion({cadena(tomo)}, '
               f'{tupla(alias[p] + ".soluciones" for p in con_autoev)})')
    ind = json.load(open(os.path.join(DATOS, f'indice-tomo{tomo}.json'), encoding='utf-8'))
    out.append('#let entradas = (')
    for e in ind['entradas']:
        out.append(f'  ({cadena(letra_de(e["texto"]))}, {cadena(e["texto"])}, '
                   f'{tupla(cadena(x) for x in e["principales"])}, {tupla(cadena(x) for x in e["otras"])}),')
    out.append(')')
    out.append(f'#let indice = indice-alfabetico({cadena(tomo)}, entradas)')
    return '\n'.join(out) + '\n'


# ------------------------------------------------------------------------------------- degree page
def capitulos_de(lista):
    """['cap01', 'cap24'] → '1, 23' (book numbers, in order; appendices as letters)."""
    orden = [x[0] for x in partes_del_libro()]
    nums = [num_parte(p) for p in sorted(set(lista), key=orden.index)]
    return ', '.join(nums)


def mapa_competencias():
    por_comp = collections.defaultdict(set)
    por_materia = collections.defaultdict(set)
    for p, info, t in partes_del_libro():
        g = RED[p]['grado']
        for c in g['competencias']:
            por_comp[c].add(p)
        for m in g['materias']:
            por_materia[m].add(p)
    for c in HUECOS['competencias']:
        for x in c['cubren']:
            por_comp[c['codigo']].add(x['parte'])
    return por_comp, por_materia


def typ_grado():
    por_comp, por_materia = mapa_competencias()
    f = COMPETENCIAS['fuente']
    supuesto = ('Este libro no es el texto de una asignatura concreta, pero cubre buena parte de las materias de '
                'electrónica de un grado de ingeniería. Como referencia se toma el Grado en Ingeniería Electrónica '
                'Industrial y Automática, que habilita para la profesión de ingeniero técnico industrial en la '
                'especialidad de electrónica industrial, y cuyas competencias mínimas fija la Orden CIN/351/2009. '
                'Las tablas relacionan cada competencia con los capítulos que la desarrollan; la cobertura es una '
                'valoración del contenido real de los capítulos, no de sus títulos. Los créditos son los de cada '
                'módulo según la orden; el reparto en asignaturas varía de una universidad a otra.')
    fuente = (f'Fuente: {f["norma"]} ({f["boe"]}; {f["id"]}), {f["apartado"]}. Texto de las competencias '
              f'copiado del BOE. {f["nota_codigos"]}')
    mods = []
    cob_txt = {'completa': 'Completa', 'parcial': 'Parcial', 'ninguna': 'Ninguna'}
    for m in COMPETENCIAS['modulos']:
        if not m['competencias']:
            continue
        filas = []
        for c in m['competencias']:
            k = c['codigo']
            caps = capitulos_de(por_comp.get(k, []))
            cob = cob_txt.get(COBERTURA.get(k), 'Fuera del alcance' if k in FUERA else '—')
            filas.append(f'({cadena(k)}, {texto(c["texto"])}, {texto(caps or "—")}, {texto(cob)})')
        mods.append(f'({texto(m["nombre"])}, {cadena(str(m["ects"]))}, {tupla(filas)})')
    mats = []
    for m, nombre in MATERIAS.items():
        if por_materia.get(m):
            mats.append(f'({texto(nombre)}, {texto(capitulos_de(por_materia[m]))})')
    fuera = ('Las competencias marcadas «Fuera del alcance» pertenecen a materias ajenas a un libro de electrónica '
             '(química, mecánica, materiales, fluidos, empresa, gestión de proyectos); el detalle y las carencias de '
             'las demás están en el documento de análisis de huecos (HUECOS.md). Trabajo fin de grado: '
             f'{[m["ects"] for m in COMPETENCIAS["modulos"] if m["id"] == "TFG"][0]} ECTS según la orden.')
    out = [CABECERA.format(f='grado.typ', p='competencias'), '#import "paratexto.typ": *', '',
           f'#let correspondencia = correspondencia-grado({texto(supuesto)}, {texto(fuente)},',
           f'  {tupla(mods)},', f'  {tupla(mats)},', f'  {texto(fuera)})']
    return '\n'.join(out) + '\n'


# ------------------------------------------------------------------------------------- gap analysis
def huecos():
    por_comp, _ = mapa_competencias()
    titulo_de = {p: INDICE['partes'][p]['titulo'] for p in INDICE['partes']}
    comps = []
    for c in HUECOS['competencias']:
        comps.append({**c, 'texto': TEXTO_COMP[c['codigo']],
                      'cubren': [{**x, 'capitulo': NOMBRE_PARTE.get(x['parte']), 'titulo': titulo_de[x['parte']]}
                                 for x in c['cubren']]})
    props = [{**p, 'prerrequisitos_capitulos': [NOMBRE_PARTE[x] for x in p['prerrequisitos']]}
             for p in HUECOS['propuestas']]
    datos = {'fuente': COMPETENCIAS['fuente'], 'referencia': 'Grado en Ingeniería Electrónica Industrial y Automática',
             'fuera_alcance': [{**x, 'texto': TEXTO_COMP[x['codigo']]} for x in HUECOS['fuera_alcance']],
             'competencias': comps, 'propuestas': props}
    guardar(os.path.join(AQUI, 'huecos.json'), datos)

    md = ['# Análisis de huecos frente a la Orden CIN/351/2009', '',
          'Borrador para el autor. Referencia: **Grado en Ingeniería Electrónica Industrial y Automática** (supuesto; '
          'es el grado que habilita para la especialidad de electrónica industrial de la profesión de ingeniero técnico '
          'industrial). Competencias: Orden CIN/351/2009, de 9 de febrero, '
          f'{COMPETENCIAS["fuente"]["boe"]} ({COMPETENCIAS["fuente"]["id"]}), '
          f'{COMPETENCIAS["fuente"]["apartado"]}: <{COMPETENCIAS["fuente"]["url"]}>. '
          f'{COMPETENCIAS["fuente"]["nota_codigos"]}', '',
          'Método: la cobertura se ha valorado sobre el contenido de los capítulos (títulos de sección y de '
          'apartado, primeras frases y texto completo de `web/public/libro/partes/*.json`), con una búsqueda de '
          'términos por tema (`datos/_evidencias.json`) para confirmar presencias y ausencias. Los números de '
          'capítulo y sección son los impresos (el fichero `cap24.json` es el capítulo 23). «Completa» significa '
          'que el libro cubre lo que una asignatura de grado espera de esa competencia; «parcial», que falta '
          'algún bloque que se espera; «ninguna», que no hay contenido. No se cuenta como hueco lo que un libro '
          'de electrónica no tiene por qué tratar.', '']
    cnt = collections.Counter(c['cobertura'] for c in comps)
    md += ['## Resumen', '',
           f'- En el alcance: {len(comps)} competencias — {cnt["completa"]} completas, {cnt["parcial"]} parciales, '
           f'{cnt["ninguna"]} sin cobertura.',
           f'- Fuera del alcance: {len(HUECOS["fuera_alcance"])} competencias (lista al final).',
           f'- Propuestas: {len(props)} — ' + ', '.join(
               f'{sum(1 for p in props if p["prioridad"] == k)} {pl}'
               for k, pl in (('esencial', 'esenciales'), ('recomendable', 'recomendables'), ('opcional', 'opcionales'))) +
           f'; unas {sum(p["paginas"] for p in props)} páginas en total '
           f'({sum(p["paginas"] for p in props if p["prioridad"] == "esencial")} las esenciales).', '',
           '| Código | Competencia (abreviada) | Cobertura | Capítulos que la cubren | Propuestas |',
           '|---|---|---|---|---|']
    for c in comps:
        caps = ', '.join(x['capitulo'].replace('Capítulo ', '').replace('Apéndice ', '') for x in c['cubren']) or '—'
        md.append(f'| {c["codigo"]} | {CORTO[c["codigo"]]} | {c["cobertura"]} | {caps} | '
                  f'{", ".join(c["huecos"]) or "—"} |')
    md += ['', '## Competencias en el alcance', '']
    for c in comps:
        md += [f'### {c["codigo"]} — {c["cobertura"]}', '', f'> {c["texto"]}', '', c['comentario'], '']
        for x in c['cubren']:
            md.append(f'- {x["capitulo"]} ({x["titulo"]}), {x["secciones"]}: {x["nota"]}.')
        if c['huecos']:
            md += ['', 'Propuestas: ' + ', '.join(c['huecos']) + '.']
        md.append('')
    md += ['## Propuestas de contenido nuevo', '',
           'Por prioridad. Las páginas son una estimación con la maqueta 1.1 (200 × 265 mm, columna de 116 mm).', '']
    orden = {'esencial': 0, 'recomendable': 1, 'opcional': 2}
    for p in sorted(props, key=lambda x: (orden[x['prioridad']], x['id'])):
        md += [f'### {p["id"]} — {p["titulo"]} ({p["prioridad"]}, {p["tipo"]}, ~{p["paginas"]} págs.)', '',
               f'- Dónde: {p["ubicacion"]}',
               f'- Competencias: {", ".join(p["competencias"])}.',
               f'- Requisitos en el libro: {", ".join(p["prerrequisitos_capitulos"])}.',
               '- Esquema:']
        md += [f'  {i + 1}. {l}' for i, l in enumerate(p['esquema'])]
        md.append('')
    md += ['## Fuera del alcance', '']
    for x in HUECOS['fuera_alcance']:
        md.append(f'- **{x["codigo"]}** — {x["motivo"]}')
    md.append('')
    open(os.path.join(AQUI, 'HUECOS.md'), 'w', encoding='utf-8').write('\n'.join(md))
    return comps, props


# ------------------------------------------------------------------------------------- main
def main():
    os.makedirs(SALIDA, exist_ok=True)
    tomos = collections.OrderedDict()
    for p, info, tomo in partes_del_libro():
        ruta = os.path.join(DATOS, f'{p}.json')
        d = json.load(open(ruta, encoding='utf-8'))
        r = RED[p]
        d['redactado'] = {
            'aviso': 'Texto redactado para revisión del autor (no procede del libro).',
            'objetivos': r['objetivos'], 'resumen': r['resumen'],
            'grado': {'materias': [MATERIAS.get(m, m) for m in r['grado']['materias']],
                      'competencias': [{'codigo': c, 'texto': TEXTO_COMP[c]} for c in r['grado']['competencias']]},
            'lecturas': [{'id': l, **LECTURAS[l], 'referencia': referencia(l)} for l in r.get('lecturas', [])],
        }
        guardar(ruta, d)
        # (1.2: a part whose whole paratext the book wrote itself, kept by importar_libro.py)
        propio = os.path.join(REDACCION, 'libro41', f'{p}.typ')
        open(os.path.join(SALIDA, f'{p}.typ'), 'w', encoding='utf-8').write(
            open(propio, encoding='utf-8').read() if os.path.exists(propio) else typ_parte(d, r))
        tomos.setdefault(tomo, []).append(p)
    for t, ps in tomos.items():
        open(os.path.join(SALIDA, f'tomo{t}.typ'), 'w', encoding='utf-8').write(typ_tomo(t, ps))
    # (1.2: since 4.1 the degree page is the book's — written numbers of 4.1 and the CIN/351/2009 audit —, kept in
    # redaccion/grado.typ by importar_libro.py; typ_grado() is the generated draft it started from)
    propio = os.path.join(REDACCION, 'grado.typ')
    open(os.path.join(SALIDA, 'grado.typ'), 'w', encoding='utf-8').write(
        open(propio, encoding='utf-8').read() if os.path.exists(propio) else typ_grado())
    if os.path.exists(os.path.join(AQUI, 'paratexto.typ')):
        shutil.copy2(os.path.join(AQUI, 'paratexto.typ'), os.path.join(SALIDA, 'paratexto.typ'))
    comps, props = huecos()
    print('partes', sum(len(v) for v in tomos.values()), 'tomos', len(tomos), 'competencias', len(comps),
          'propuestas', len(props))


if __name__ == '__main__':
    main()
