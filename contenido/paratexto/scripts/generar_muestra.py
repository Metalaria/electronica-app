"""Writes muestra-paratexto.typ: the paratext pages around a skeleton of chapter 1 (real headings and
first paragraphs from the app's cap01.json, so the page references resolve), then the volume-end
pages (self-assessment solutions and alphabetical index) restricted to chapter 1."""
import json
import os
import re

from comun import AQUI, DATOS, cadena, cargar, html_a_typst, letra_de

PARTE = 'cap01'
REFS = cargar('refs.json')


def primera_frase(h, n=45):
    t = html_a_typst(h)
    w = t.split(' ')
    return ' '.join(w[:n]) + (' …' if len(w) > n else '')


def main():
    d = cargar(f'partes/{PARTE}.json')
    datos = json.load(open(os.path.join(DATOS, f'{PARTE}.json'), encoding='utf-8'))
    niveles = {e['id']: e['nivel'] for e in datos['dificultad']}
    cuerpo = []
    vistos_h2 = set()
    intro_hecha = False
    esperando_p = None          # label of the heading whose first paragraph is still to come
    ejercicios = []
    for b in d['bloques']:
        t = b.get('t')
        if t == 'h2':
            intro_hecha = True
            cuerpo.append(f'\n== {html_a_typst(b["html"])} <{b["label"]}>\n')
            vistos_h2.add(b['label'])
            esperando_p = b['label']
        elif t == 'h3' and b.get('label'):
            marca = f'#nivel-de(p01.niveles, "{b["label"]}") ' if b['label'] in niveles else ''
            sub = '#subnum() ' if b.get('num') else ''
            cuerpo.append(f'\n=== {sub}{marca}{html_a_typst(b["html"])} <{b["label"]}>\n')
            esperando_p = b['label']
        elif t == 'p':
            if not intro_hecha:
                cuerpo.append(html_a_typst(b['html']) + '\n')
            elif esperando_p:
                cuerpo.append(primera_frase(b['html']) + '\n')
                cuerpo.append('#recorte()\n')
                esperando_p = None
        elif t == 'ejercicios':
            for it in b['items']:
                ps = [x for x in it['bloques'] if x.get('t') == 'p']
                txt = ' #linebreak() '.join(html_a_typst(x['html']) for x in ps)
                ejercicios.append(f'  #ejercicio[#nivel-de(p01.niveles, "{it["label"]}")'
                                  f'{txt}] <{it["label"]}>\n')
    # numbers for #nr of references that point outside the skeleton
    texto = '\n'.join(cuerpo + ejercicios)
    claves = sorted(set(re.findall(r'#nr\("([^"]+)"\)', texto)))
    nums = ',\n'.join(f'  {cadena(k)}: {cadena(REFS[k]["num"])}' for k in claves if k in REFS)
    # alphabetical index restricted to the chapter's labels
    ind = json.load(open(os.path.join(DATOS, 'indice-tomoI.json'), encoding='utf-8'))

    def del_capitulo(lab):
        return REFS.get(lab, {}).get('parte') == PARTE

    entradas = []
    for e in ind['entradas']:
        pr = [x for x in e['principales'] if del_capitulo(x)]
        ot = [x for x in e['otras'] if del_capitulo(x)]
        if pr or ot:
            entradas.append(f'  ({cadena(letra_de(e["texto"]))}, {cadena(e["texto"])}, '
                            f'({"".join(cadena(x) + ", " for x in pr)}), ({"".join(cadena(x) + ", " for x in ot)})),')
    out = f'''// muestra-paratexto.typ: generated by scripts/generar_muestra.py. Sample of the paratext pages for
// chapter 1 around a skeleton of the chapter (real headings and first paragraphs), so that page
// references resolve. Compile from libro11/ as root:  python3 scripts/compilar.py  (see LEEME in REVISAR.md)
#import "../plantilla/plantilla.typ": *
#import "paratexto.typ": *
#import "cap01.typ" as p01
#import "grado.typ": correspondencia

// Sample-only: marks where the omitted chapter text would continue.
#let recorte() = block(width: 100%, above: 0.9em, below: 1.2em, inset: (y: 3pt),
  stroke: (bottom: (paint: FILETE, thickness: 0.6pt, dash: "dashed")),
  align(center, text(font: TITULAR, size: 7.5pt, fill: GRIS)[texto del capítulo omitido en la muestra]))

#let NUMS = (
{nums}
)

#show: libro.with(numeros: NUMS, primer-capitulo: 1)

#correspondencia

#capitulo("1A3A5C")[{html_a_typst(d["titulo"])}] <cap-1>

#p01.inicio

{"".join(cuerpo)}
#p01.cierre

#ejercicios[
  #leyenda-niveles()
{"".join(ejercicios)}]

#soluciones-autoevaluacion("I", (p01.soluciones,))

#indice-alfabetico("I", (
{chr(10).join(entradas)}
))
'''
    open(os.path.join(AQUI, 'muestra-paratexto.typ'), 'w', encoding='utf-8').write(out)
    print('h2', len(vistos_h2), 'ejercicios', len(ejercicios), 'entradas', len(entradas), 'nr', len(claves))


if __name__ == '__main__':
    main()
