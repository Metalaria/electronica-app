"""Check Moira (precise timing mode), the 68000 of the Mega Drive and Neo Geo traces, against SingleStepTests/680x0
(one-instruction tests generated by Thomas Harte with Clock Signal's microcode-level 68000).

For every test of the chosen instruction files: final registers, RAM, and the bus accesses (read/write, byte/word,
address, value) with the cycle at which each one starts, from the test's transaction list (each entry has its
length in cycles; «n» entries are idle cycles). Moira calls the memory functions at a fixed point of each bus cycle,
so «start of the cycle (test) − Moira's clock at the call» must be one constant for every access.
Tests that end in an address error (a word access at an odd address: exception frame and timing of that
exception) are counted apart: the demos never make one.

Usage: python3 validar_m68k.py <m68k_sst binary> <cache dir> [file names …] (e.g. MOVE.w ADDQ.w Bcc)
Test files: https://github.com/SingleStepTests/680x0 (68000/v1/<name>.json.gz), MIT licence.
"""
import collections
import gzip
import json
import os
import subprocess
import sys
import urllib.request

URL = 'https://raw.githubusercontent.com/SingleStepTests/680x0/main/68000/v1/%s.json.gz'
# Instructions of the Mega Drive and Neo Geo demos, plus the most common ones in game code.
POR_DEFECTO = ('MOVE.b MOVE.w MOVE.l MOVEA.w MOVEA.l MOVE.q LEA ADD.w ADD.l SUB.w SUB.l '
               'CMP.w TST.w TST.b AND.b AND.w OR.w BTST DBcc Bcc BSR JSR JMP RTS RTE CLR.w CLR.l '
               'SWAP EXT.w LSL.w LSR.w MOVEM.w MOVEM.l MOVEtoSR MOVEfromSR').split()
REGS = ['d%d' % i for i in range(8)] + ['a%d' % i for i in range(7)] + ['usp', 'ssp', 'sr', 'pc']


def cargar(cache, nombre):
    ruta = os.path.join(cache, nombre + '.json.gz')
    if not os.path.exists(ruta):
        with urllib.request.urlopen(URL % nombre) as r, open(ruta, 'wb') as f:
            f.write(r.read())
    with gzip.open(ruta, 'rt') as f:
        return json.load(f)


def accesos(tr):
    out, t = [], 0
    for x in tr:
        if x[0] in ('r', 'w'):
            out.append((x[0], x[4][1], x[3] & 0xFFFFFF, x[5], t))
        t += x[1]
    return out, t


def main():
    exe, cache = sys.argv[1], sys.argv[2]
    os.makedirs(cache, exist_ok=True)
    nombres = sys.argv[3:] or POR_DEFECTO
    pruebas, n_acc, fallos = 0, 0, collections.Counter()
    desfase = collections.Counter()
    ciclos_mal = collections.Counter()
    errores_dir = collections.Counter()
    fallos_error_dir = collections.Counter()
    ejemplos = []
    for nombre in nombres:
        try:
            tests = cargar(cache, nombre)
        except Exception as e:  # noqa: BLE001
            print('  sin fichero %s: %s' % (nombre, e))
            continue
        entrada = []
        for k, t in enumerate(tests):
            i = t['initial']
            pf = i['prefetch']
            entrada.append('T %d' % k)
            entrada.append('R ' + ' '.join(str(i[r]) for r in REGS) + ' %d' % (pf[0] | pf[1] << 16))
            entrada += ['M %d %d' % (a, v) for a, v in i['ram']]
            entrada.append('G')
        res = subprocess.run([exe], input='\n'.join(entrada) + '\n', capture_output=True, text=True, check=True).stdout
        bloques = res.split('\nT ')
        bloques[0] = bloques[0][2:]
        for t, b in zip(tests, bloques):
            pruebas += 1
            lineas = b.strip().split('\n')[1:]
            mios = [l.split()[1:] for l in lineas if l.startswith('B ')]
            fin = [int(x) for x in next(l for l in lineas if l.startswith('F ')).split()[1:]]
            esperado = t['final']
            mal = [r for r, v in zip(REGS, fin) if esperado[r] != v]
            if [fin[19], fin[20]] != esperado['prefetch']:
                mal.append('prefetch')
            suyos, total = accesos(t['transactions'])
            # address error (odd word address): the test reads vector 3 at $00000C
            error_dir = any(x[0] == 'r' and x[3] in (12, 14) for x in t['transactions'])
            if error_dir:
                errores_dir[nombre] += 1
            total = t.get('length', total)   # the test's length (trailing internal cycles have no transaction)
            if fin[21] != total:
                mal.append('ciclos %d/%d' % (fin[21], total))
                ciclos_mal[nombre] += 1
            if len(mios) != len(suyos):
                mal.append('accesos %d/%d' % (len(mios), len(suyos)))
            else:
                for m, s in zip(mios, suyos):
                    n_acc += 1
                    rw, sz, a, v, clk = m[0], m[1], int(m[2]), int(m[3]), int(m[4])
                    if (rw, sz, a) != (s[0], s[1], s[2]) or (v & (0xFF if sz == 'b' else 0xFFFF)) != (s[3] & (0xFF if sz == 'b' else 0xFFFF)):
                        mal.append('acceso %r/%r' % (m, s))
                        break
                    if not error_dir:
                        desfase[s[4] - clk] += 1
            if mal and error_dir:
                fallos_error_dir[nombre] += 1
                continue
            if mal:
                fallos[nombre] += 1
                if len(ejemplos) < 10:
                    ejemplos.append((t['name'], mal[:3]))
    print('validar_m68k: %d pruebas, %d accesos al bus comparados, %d pruebas con diferencias (sin contar los errores de dirección)'
          % (pruebas, n_acc, sum(fallos.values())))
    print('  pruebas con error de dirección (acceso a palabra en dirección impar): %d, de ellas con diferencias: %d'
          % (sum(errores_dir.values()), sum(fallos_error_dir.values())))
    print('  inicio del ciclo de bus (prueba) − reloj de Moira en la llamada: %s' % dict(desfase))
    for n, c in fallos.most_common():
        print('  fallos en %s: %d (duración distinta: %d)' % (n, c, ciclos_mal[n]))
    for e in ejemplos:
        print('  ejemplo:', e)
    return 1 if fallos else 0


if __name__ == '__main__':
    sys.exit(main())
