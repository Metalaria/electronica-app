def V(fam, esq=None, graf=None):
    """One formula: family, optional schematic (template, slots) and optional plot (kind, slots)."""
    out = {'fam': fam}
    if esq:
        out['esq'] = esq
    if graf:
        out['graf'] = graf
    return out


def R(fam, x=None):
    """Only the generic response plot, with its preferred horizontal variable."""
    return V(fam, graf=('respuesta', {'x': x}) if x else None)


