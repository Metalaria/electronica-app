#!/usr/bin/env node
// Extracts ngspice (WebAssembly) from the npm package eecircuit-engine into files the app can load lazily.
//
// The package ships one 20 MB ES module: the Emscripten factory of ngspice with the .wasm inlined twice as
// base64, about 4 MB of foundry model cards and a small driver class. The app only needs the factory and the
// binary, and drives ngspice itself (see src/simulador/worker.ts), so this script writes:
//   src/simulador/motor/ngspice.js   the Emscripten factory (≈ 150 kB), default export
//   public/ngspice/ngspice.wasm      the binary (≈ 6 MB), fetched only when the simulator is opened
//   public/ngspice/LICENSE.txt       the package licence (MIT) and the ngspice licence note
// Both outputs are generated (git-ignored) and rebuilt by `npm run dev|build|check` when missing or stale.
//
// Usage: node scripts/ngspice.mjs [--force]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// The package's "exports" map hides package.json (and its CommonJS entry does not exist), so resolve the ES
// entry point and walk up to the package root.
let pkgDir = path.dirname(fileURLToPath(import.meta.resolve('eecircuit-engine')));
while (!fs.existsSync(path.join(pkgDir, 'package.json'))) pkgDir = path.dirname(pkgDir);
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const EXPECTED = '1.8.0';
if (pkg.version !== EXPECTED) {
  // The extraction relies on the layout of this exact build; check it again before accepting another one.
  console.error(`ngspice.mjs: eecircuit-engine ${pkg.version} instalado, se esperaba ${EXPECTED}.`);
  process.exit(1);
}

const src = path.join(pkgDir, 'dist', 'eecircuit-engine.mjs');
const outJs = path.join(web, 'src', 'simulador', 'motor', 'ngspice.js');
const outDir = path.join(web, 'public', 'ngspice');
const outWasm = path.join(outDir, 'ngspice.wasm');
const outLic = path.join(outDir, 'LICENSE.txt');
const stamp = `// Generated by scripts/ngspice.mjs from eecircuit-engine ${pkg.version}. Do not edit.\n`;

const force = process.argv.includes('--force');
if (!force && fs.existsSync(outWasm) && fs.existsSync(outJs) && fs.readFileSync(outJs, 'utf8').startsWith(stamp)) {
  process.exit(0);
}

const text = fs.readFileSync(src, 'utf8');

// 1. The factory: from the start of the spice.js region to the start of the next region.
const start = text.indexOf('//#region src/spice.js');
const end = text.indexOf('//#region', start + 10);
if (start < 0 || end < 0) throw new Error('ngspice.mjs: no se encuentra la región src/spice.js');
let factory = text.slice(start, end).replace(/\/\/#endregion\s*$/, '');

// 2. The inlined binary: `t.locateFile ? l("spice.wasm") : new URL("data:application/wasm;base64,…").href`
//    (the exact tail varies); keep the bytes once, as a file, and always go through locateFile.
const dataRe = /new URL\("data:application\/wasm;base64,([A-Za-z0-9+/=]+)"(?:\s*,\s*[^)]*)?\)(?:\.href)?/;
const m = factory.match(dataRe);
if (!m) throw new Error('ngspice.mjs: no se encuentra el binario incrustado');
const wasm = Buffer.from(m[1], 'base64');
if (wasm.readUInt32BE(0) !== 0x0061736d) throw new Error('ngspice.mjs: el binario no es WebAssembly');
factory = factory.replace(dataRe, 'l("spice.wasm")');
if (factory.includes('data:application/wasm')) throw new Error('ngspice.mjs: quedan binarios incrustados');

// 3. The factory starts with `async function e(e = {})`; export it.
const decl = factory.match(/async function (\w+)\(\w+ = \{\}\)/);
if (!decl) throw new Error('ngspice.mjs: no se encuentra la función de arranque');
const body = `${stamp}/* eslint-disable */\n// @ts-nocheck\n${factory}\nexport default ${decl[1]};\n`;

fs.mkdirSync(path.dirname(outJs), { recursive: true });
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outWasm, wasm);
fs.writeFileSync(outJs, body);
fs.writeFileSync(
  outLic,
  `ngspice compilado a WebAssembly por el paquete npm eecircuit-engine ${pkg.version}\n` +
    `(https://github.com/eelab-dev/EEcircuit-engine), licencia MIT:\n\n` +
    fs.readFileSync(path.join(pkgDir, 'LICENSE'), 'utf8') +
    `\nngspice (https://ngspice.sourceforge.io) se distribuye con licencia BSD modificada (3 cláusulas);\n` +
    `algunas partes (XSPICE, modelos) tienen sus propias licencias libres, descritas en su distribución.\n`,
);
console.log(
  `ngspice.mjs: ${path.relative(web, outJs)} (${(body.length / 1024).toFixed(0)} kB), ` +
    `${path.relative(web, outWasm)} (${(wasm.length / 1048576).toFixed(1)} MB)`,
);
