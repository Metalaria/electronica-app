import { datos } from './navegador.ts';
import { writeFileSync } from 'node:fs';
setTimeout(() => { console.error('TIMEOUT'); process.exit(3); }, 60000).unref?.();
const [raiz, salida] = process.argv.slice(2);
let t = 1_760_000_000_000;
Date.now = () => (t += 1000);
const imp = (p: string) => import(`file://${raiz}/${p}`);
const U = await imp('lib/usuario.svelte.ts');
const A = await imp('lib/aprendizaje.svelte.ts');
const Rp = await imp('componentes/repaso/estado.svelte.ts');
const C = await imp('componentes/calculadoras/datos.svelte.ts');
const E = await imp('componentes/editor/circuitos.svelte.ts');
const P = await imp('componentes/protoboard/circuitos.svelte.ts');
const D = await imp('lib/progreso-diario.svelte.ts');
const L = await imp('lib/lecciones.svelte.ts');
await U.cargarUsuario(); await A.cargarAprendizaje(); await Rp.cargarRepaso(); await C.cargarFavoritos();
await E.cargarCircuitos(); await P.cargarMontajes(); await D.cargarProgresoDiario(); await L.cargarLecciones();
const espera = (ms: number) => new Promise((r) => setTimeout(r, ms));
for (let i = 1; i <= 12; i++) U.guardarPosicion(`cap${String(i).padStart(2, '0')}`, { b: i * 3, sec: `sec:${i}.1` });
for (let i = 1; i <= 15; i++) U.alternarMarcador({ label: `eq:${i}`, parte: `cap0${(i % 9) + 1}`, titulo: `Ecuación ${i}` });
U.alternarMarcador({ label: 'eq:3', parte: 'cap04', titulo: 'x' }); // removed again (a deletion mark)
for (let i = 1; i <= 20; i++) U.guardarNota({ label: `fig:${i}`, parte: `cap0${(i % 9) + 1}`, titulo: `Figura ${i}` }, `nota número ${i} con acentos áéí «comillas»`);
U.guardarNota({ label: 'fig:7', parte: 'cap08', titulo: 'Figura 7' }, '');
await espera(1500);
for (let i = 1; i <= 25; i++) A.registrarIntento(`ej:${i}`, { a: String(i), b: '1k' }, ['a'], i % 2 === 0);
A.usarPista('ej:3', 2); A.verSolucion('ej:4'); A.taparProblema('ej:5', true); A.autoevaluar('ej:30', true);
A.reiniciarEjercicio('ej:6');
for (let i = 1; i <= 30; i++) A.marcarLeida(`cap0${(i % 9) + 1}`, `sec:${i}`, true);
A.marcarLeida('cap02', 'sec:2', false);
for (let i = 1; i <= 10; i++) A.guardarPasos(`cap0${(i % 9) + 1}:${i * 7}`, i % 5);
await espera(1500);
for (let i = 1; i <= 40; i++) Rp.calificar(`t:${i}`, ((i % 4) + 1), Date.now());
const d = Rp.calificar('t:99', 3, Date.now()); Rp.deshacer(d);
Rp.ponerAjustes({ nuevasDia: 15, inversas: true, mazo: 'cap05' });
for (let i = 1; i <= 8; i++) Rp.registrarTest(`cap0${i}`, i, 10, Date.now());
for (let i = 1; i <= 12; i++) Rp.registrarRespuesta(`p:${i}`, `cap0${(i % 9) + 1}`, false, Date.now());
Rp.registrarRespuesta('p:2', 'cap03', true, Date.now()); Rp.quitarFallo('p:4');
for (let i = 1; i <= 33; i++) Rp.registrarExamen([`cap0${(i % 9) + 1}`], i % 10, 10, Date.now());
await espera(1500);
for (const id of ['senoide', 'carga-rc', 'tau-rc', 'db-tension', 'bode-polo']) C.alternarFavorita(id);
C.alternarFavorita('tau-rc');
const doc = (n: number) => ({ version: 1, titulo: `Circuito ${n}`, componentes: Array.from({ length: 6 }, (_, k) => ({ id: `R${k}`, tipo: 'R', x: k * 10, y: n, rot: 0, valor: '1k', props: { tol: 5 } })), cables: [{ id: 'w1', puntos: [[0, 0], [10, 0], [10, n]] }], origen: null });
const ids: string[] = [];
for (let i = 1; i <= 6; i++) ids.push(await E.guardarNuevo(`Circuito ${i}`, doc(i)));
await E.actualizar(ids[1], { ...doc(2), titulo: 'Circuito 2 editado' });
await E.renombrar(ids[2], 'Renombrado'); await E.borrar(ids[3]);
const pdoc = (n: number) => ({ version: 1, titulo: `Placa ${n}`, piezas: [{ id: 'p1', tipo: 'resistencia', pos: [3, n], valor: '220' }], cables: [{ id: 'c1', de: [1, 1], a: [5, n], color: 'rojo' }] });
const pids: string[] = [];
for (let i = 1; i <= 4; i++) pids.push(await P.guardarMontaje(`Placa ${i}`, pdoc(i)));
await P.borrarMontaje(pids[0]); await P.actualizarMontaje(pids[1], { ...pdoc(2), titulo: 'Placa 2 bis' });
for (let i = 0; i < 7; i++) D.registrarActividad(i % 2 ? 'paso' : 'pregunta', 3);
D.ponerObjetivo({ tipo: 'preguntas', n: 7 });
for (let i = 1; i <= 6; i++) { L.anotarPaso(`cap0${i}`, `sec:${i}`, 1, 5); L.completarPaso(`cap0${i}`, `sec:${i}`, 2, 5); }
L.completarLeccion('cap01', 'sec:1', 5);
await espera(2000);
U.volcar(); Rp.volcarRepaso(); window.dispatchEvent(new Event('pagehide')); document.dispatchEvent(new Event('visibilitychange'));
await espera(2000);
const out: Record<string, string> = {};
for (const [k, v] of datos) out[k] = v;
writeFileSync(salida, JSON.stringify(out, null, 1));
console.log('claves', Object.keys(out).join(' '));
process.exit(0);
